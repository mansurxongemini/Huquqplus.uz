def clean_legal_ru(legal: str) -> str:
    """Translates legal basis enactment citations to authentic, standard Russian legal citations."""
    if not legal:
        return "Действующее законодательство Республики Узбекистан"

    res = legal

    # Codes
    res = re.sub(r'Mehnat kodeksi (\d+)-moddasi', r'Трудовой кодекс Республики Узбекистан, статья \1', res)
    res = re.sub(r'Soliq kodeksi (\d+)-moddasi', r'Налоговый кодекс Республики Узбекистан, статья \1', res)
    res = re.sub(r'Mehnat kodeksi', r'Трудовой кодекс Республики Узбекистан', res)
    res = re.sub(r'Soliq kodeksi', r'Налоговый кодекс Республики Узбекистан', res)

    # Laws
    res = re.sub(r'Qonun O‘RQ-(\d+)', r'Закон Республики Узбекистан ЗРУ-\1', res)
    res = re.sub(r'Qonun', r'Закон', res)

    # Decrees and Resolutions
    res = re.sub(r'Prezident Farmoni PF-(\d+)', r'Указ Президента Республики Узбекистан УП-\1', res)
    res = re.sub(r'Prezident Qarori PQ-(\d+)', r'Постановление Президента Республики Узбекистан ПП-\1', res)
    res = re.sub(r'Vazirlar Mahkamasining (\d+)-son qarori', r'Постановление Кабинета Министров от \1 (ПКМ-\1)', res)
    res = re.sub(r'(\d+)-son qaror(?:i)?', r'Постановление № \1', res)

    # Articles
    res = re.sub(r'(\d+)-modda(?:si)?', r'статья \1', res)
    res = re.sub(r'modda(?:si)?', r'статья', res)

    # Departmental acts
    res = re.sub(r'Idoraviy', r'Ведомственный акт', res)

    # Formatting cleanups
    res = re.sub(r',\s*,', r',', res)
    res = re.sub(r'\s+', ' ', res).strip()
    res = re.sub(r',\s*$', '', res).strip()

    return res


